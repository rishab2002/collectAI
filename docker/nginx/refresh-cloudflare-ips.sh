#!/bin/sh
# Regenerates both Cloudflare range files from the published lists.
#
# They have to be regenerated together: cloudflare-ips.conf drives
# `set_real_ip_from` (so $request->ip() is the visitor, not the edge) and
# cloudflare-allow.conf drives the `$from_cloudflare` geo (so the origin IP is
# not a second front door). nginx has no directive that does both, and a list that is stale in only
# one of them fails confusingly — some visitors 403, or some get throttled
# against the wrong key.
#
# Run from the repo root, then rebuild the image.

set -eu

dir="$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)"

v4="$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4)"
v6="$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6)"

if [ -z "$v4" ] || [ -z "$v6" ]; then
    echo "refusing to write: Cloudflare returned an empty list" >&2
    exit 1
fi

today="$(date -u +%Y-%m-%d)"

{
    printf '# Cloudflare edge ranges, generated by refresh-cloudflare-ips.sh on %s.\n' "$today"
    printf '# Do not edit by hand. See cloudflare-allow.conf, which is generated with it.\n\n'
    printf '%s\n' "$v4" | sed 's/^/set_real_ip_from /; s/$/;/'
    printf '\n'
    printf '%s\n' "$v6" | sed 's/^/set_real_ip_from /; s/$/;/'
    printf '\nreal_ip_header CF-Connecting-IP;\n'
} > "$dir/cloudflare-ips.conf"

{
    printf '# Cloudflare edge ranges, generated by refresh-cloudflare-ips.sh on %s.\n' "$today"
    printf '# Do not edit by hand. See cloudflare-ips.conf, which is generated with it.\n'
    printf '#\n# A geo on $realip_remote_addr, never allow/deny: the real-IP rewrite runs\n'
    printf '# first, so allow/deny would check the visitor and refuse everyone.\n\n'
    printf 'geo $realip_remote_addr $from_cloudflare {\n    default 0;\n\n'
    printf '%s\n' "$v4" | sed 's/^/    /; s/$/ 1;/'
    printf '\n'
    printf '%s\n' "$v6" | sed 's/^/    /; s/$/ 1;/'
    printf '\n    # Loopback and Docker networks: the healthcheck, and a tunnel'"'"'s cloudflared.\n'
    printf '    127.0.0.1 1;\n    ::1 1;\n    10.0.0.0/8 1;\n    172.16.0.0/12 1;\n    192.168.0.0/16 1;\n}\n'
} > "$dir/cloudflare-allow.conf"

echo "wrote $dir/cloudflare-ips.conf and $dir/cloudflare-allow.conf"
